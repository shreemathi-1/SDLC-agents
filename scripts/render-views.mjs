// Reference renderer for the requirements/ Markdown views (step 15, requirements-documentation).
// The agent writes the views itself from the templates; this script produces the golden examples the
// templates point to and lets verify-scaffold.mjs check that they stay in sync.
// CLI: node scripts/render-views.mjs <requirements.json> <out dir>
import fs from 'node:fs';
import path from 'node:path';

const BADGE = { EXPLICIT: '**[Explicit]**', INFERRED: '**[Inferred]**', RECOMMENDED: '**[Recommended]**', UNKNOWN: '**[Unknown]**' };
const TYPES = [
  ['FUNCTIONAL', 'Functional requirements'], ['NON_FUNCTIONAL', 'Non-functional requirements'], ['BUSINESS_RULE', 'Business rules'],
  ['DATA', 'Data requirements'], ['INTEGRATION', 'Integration requirements'], ['SECURITY', 'Security requirements'],
  ['COMPLIANCE', 'Compliance requirements'], ['CONSTRAINT', 'Constraints'], ['ASSUMPTION', 'Assumptions'], ['DEPENDENCY', 'External dependencies'],
];
const LEVELS = { 1: 'Level 1: quick wins', 2: 'Level 2: product enhancements', 3: 'Level 3: advanced innovation', 4: 'Level 4: future opportunities' };
const URGENCY = ['BLOCKING', 'HIGH', 'NORMAL'];
const RANK = { HIGH: 3, MEDIUM: 2, LOW: 1 };
const list = (xs) => (xs?.length ? xs.join(', ') : '—');
const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function render(d) {
  const run = d.project.last_run;
  const header = (title) => `# ${title} — ${d.project.name}\n\n> Generated from \`requirements/requirements.json\` (run ${run}). Do not edit this file by hand${title === 'Requirements specification' ? ' except the **Sign-off** table' : title === 'Innovation opportunities' ? ' except the **decision blocks**' : ''}; change the JSON and regenerate.\n`;
  const live = d.requirements.filter(r => r.status !== 'DEPRECATED');
  const visible = live.filter(r => r.client_visible);
  const openQ = d.questions.filter(q => q.status === 'OPEN');
  const out = {};

  // ---- requirements.md ----
  {
    const s = [header('Requirements specification')];
    s.push(`**Domain:** ${d.project.domain.join(', ')} · **Stories:** ${d.stories.map(x => x.id).join(', ')} · **Requirements:** ${visible.length} · **Open questions:** ${openQ.length}\n`);
    s.push('Every priority and phase below is **proposed** until the client confirms it.\n');
    s.push('## Summary\n\n| ID | Title | Type | Origin | Priority | Phase | Status |\n|---|---|---|---|---|---|---|');
    for (const r of visible) s.push(`| ${r.id} | ${cell(r.title)} | ${r.type} | ${BADGE[r.origin]} | ${r.priority} | ${r.phase} | ${r.status} |`);
    for (const [type, heading] of TYPES) {
      const rs = visible.filter(r => r.type === type);
      if (!rs.length) continue;
      s.push(`\n## ${heading}\n`);
      for (const r of rs) {
        s.push(`### ${r.id} — ${r.title} ${BADGE[r.origin]}\n\n${r.description}\n`);
        s.push(`- **Source:** ${list(r.source)}${r.promoted_from ? ` (promoted from ${r.promoted_from})` : ''} · **Priority:** ${r.priority} (${r.priority_status.toLowerCase()}) · **Phase:** ${r.phase} · **Status:** ${r.status} · **Confidence:** ${r.confidence}`);
        if (r.evidence) s.push(`- **Client's words:** "${r.evidence}"`);
        if (r.rationale) s.push(`- **Rationale:** ${r.rationale}`);
        if (r.nfr_metric) s.push(`- **Metric:** ${r.nfr_metric.metric} · **Target:** ${r.nfr_metric.target} · **Measured by:** ${r.nfr_metric.measurement}`);
        if (r.rule_category) s.push(`- **Rule category:** ${r.rule_category}`);
        s.push(`- **Business rules:** ${list(r.business_rules)} · **Depends on:** ${list(r.dependencies)} · **Risks:** ${list(r.risks)}`);
        if (r.open_questions.length) s.push(`- **Open questions:** ${r.open_questions.join(', ')} (see open-questions.md)`);
        if (r.priority_reason) s.push(`- **Why this priority:** ${r.priority_reason}`);
        if (r.source_refs?.length) s.push(`- **Design:** ${r.source_refs.join(' · ')}`);
        s.push(`- **Acceptance criteria:**${r.acceptance_criteria.length ? '' : ' none yet'}`);
        for (const a of r.acceptance_criteria) s.push(`  - ${a}`);
        s.push('');
      }
    }
    s.push('## Sign-off\n\nTo approve, write `APPROVED` (or `CHANGES` with a note), your name and the date in a row. The agent copies each decision into `requirements.json` on its next run and records it as a human change.\n');
    s.push('| ID | Title | Current status | Decision | By | Date | Note |\n|---|---|---|---|---|---|---|');
    for (const r of visible) s.push(`| ${r.id} | ${cell(r.title)} | ${r.status} |  |  |  |  |`);
    out['requirements.md'] = s.join('\n') + '\n';
  }

  // ---- client-summary.md ----
  {
    const s = [header('Client summary')];
    s.push(`## The problem\n\n${d.project.business_problem ?? d.project.description}\n`);
    if (d.project.business_objectives?.length) s.push(`## Objectives\n\n${d.project.business_objectives.map(o => `- ${o}`).join('\n')}\n`);
    const mvp = visible.filter(r => r.phase === 'MVP');
    s.push(`## Proposed first release (MVP)\n\n${mvp.map(r => `- **${r.id}** ${r.title} ${BADGE[r.origin]} (${r.priority})`).join('\n')}\n`);
    const later = visible.filter(r => r.phase !== 'MVP');
    if (later.length) s.push(`## Later phases\n\n${later.map(r => `- **${r.id}** ${r.title}: ${r.phase}`).join('\n')}\n`);
    const blocking = openQ.filter(q => q.audience === 'CLIENT' && q.urgency === 'BLOCKING');
    s.push(`## Decisions we need from you first\n\n${blocking.length ? blocking.map(q => `- **${q.id}** ${q.text}`).join('\n') : 'None.'}\n\nAll ${openQ.filter(q => q.audience === 'CLIENT').length} client questions are in open-questions.md.\n`);
    const bigRisks = d.risks.filter(k => k.client_visible !== false && k.impact === 'HIGH');
    s.push(`## Main risks\n\n${bigRisks.length ? bigRisks.map(k => `- **${k.id}** ${k.title}: ${k.mitigation}`).join('\n') : 'None rated high impact.'}\n`);
    const ideas = [...d.innovations].filter(i => i.decision !== 'REJECT').sort((a, b) => b.score.weighted_total - a.score.weighted_total).slice(0, 5);
    if (ideas.length) s.push(`## Ideas for discussion (not part of the requirements)\n\n${ideas.map(i => `- **${i.id}** ${i.title}: ${i.user_value}`).join('\n')}\n\nThe full list of ${d.innovations.length} ideas is in innovation-opportunities.md.\n`);
    s.push('## Next steps\n\n1. Answer the questions above.\n2. Review the proposed priorities in requirements.md and sign off.\n3. Mark the ideas you want to pursue in innovation-opportunities.md.\n');
    out['client-summary.md'] = s.join('\n');
  }

  // ---- open-questions.md ----
  {
    const s = [header('Open questions')];
    s.push(`${openQ.length} open questions. To answer one, tell the agent in chat (for example "Q-004: no account; match name, date of birth and phone"). It records the answer as yours.\n`);
    for (const [aud, heading] of [['CLIENT', 'For the client'], ['INTERNAL', 'For the team (internal)']]) {
      const qs = openQ.filter(q => q.audience === aud);
      s.push(`## ${heading} (${qs.length})\n`);
      for (const u of URGENCY) for (const q of qs.filter(q => (q.urgency ?? 'NORMAL') === u)) {
        s.push(`### ${q.id} [${u}] ${q.text}\n`);
        s.push(`- **Blocks:** ${list(q.blocks)}${q.category ? ` · **Category:** ${q.category}` : ''}`);
        if (q.options?.length) s.push(`- **Options:** ${q.options.join(' / ')}`);
        s.push(`- **Suggested default:** ${q.suggested_default_option}\n`);
      }
    }
    const closed = d.questions.filter(q => q.status !== 'OPEN');
    if (closed.length) {
      s.push(`## Answered and withdrawn (${closed.length})\n`);
      for (const q of closed) s.push(`- **${q.id}** ${q.status}: ${q.status === 'ANSWERED' ? `${q.answer} (${q.answered_by}, ${q.answered_on})` : q.note}`);
      s.push('');
    }
    out['open-questions.md'] = s.join('\n');
  }

  // ---- innovation-opportunities.md ----
  {
    const s = [header('Innovation opportunities')];
    s.push(`These are **ideas, not requirements**. Nothing here is built unless you set its decision to \`ACCEPT\` and run \`promote\`.\n\nTo decide, edit the decision block under an idea: replace \`PENDING\` with \`ACCEPT\`, \`REJECT\` or \`DEFER\`, and fill in the reason, your name and the date. \`requirements/.state/innovation-decisions.json\` holds the same decisions; if they disagree, the JSON wins and the agent reports the conflict.\n`);
    s.push('| ID | Idea | Level | Score | Phase | Decision |\n|---|---|---|---|---|---|');
    for (const i of d.innovations) s.push(`| ${i.id} | ${cell(i.title)}${i.generated ? ' *(bold bet)*' : ''} | L${i.level} | ${i.score.weighted_total.toFixed(2)} | ${i.recommended_phase} | ${i.decision} |`);
    for (const lv of [1, 2, 3, 4]) {
      const is = d.innovations.filter(i => i.level === lv);
      if (!is.length) continue;
      s.push(`\n## ${LEVELS[lv]}\n`);
      for (const i of is) {
        s.push(`### ${i.id} — ${i.title}${i.generated ? ' *(bold bet)*' : ''}\n\n${i.description}\n`);
        s.push(`- **Problem solved:** ${i.problem_solved}\n- **For users:** ${i.user_value}\n- **For the business:** ${i.business_value}\n- **Why it fits:** ${i.relevance_reason}`);
        s.push(`- **Complexity:** ${i.complexity} · **Suggested phase:** ${i.recommended_phase} · **Score:** ${i.score.weighted_total.toFixed(2)} (relevance ${i.score.relevance}, user ${i.score.user_value}, business ${i.score.business_value}, effort ${i.score.effort_inverse}, risk ${i.score.risk_inverse})`);
        s.push(`- **Builds on:** ${list(i.dependencies)}\n- **Risks:** ${list(i.risks)}\n- **Technology:** ${list(i.technology)}\n`);
        s.push(`<!-- decision:${i.id} -->\n**Decision:** ${i.decision}\n**Reason:** ${i.decision_reason ?? ''}\n**Decided by:** ${i.decided_by ?? ''}\n**Date:** ${i.decided_on ?? ''}\n<!-- /decision -->\n`);
      }
    }
    out['innovation-opportunities.md'] = s.join('\n');
  }

  // ---- tech-trends.md ----
  {
    const s = [header('Technology trends')];
    s.push('What comparable products are doing now. These are context for decisions, not requirements or ideas.\n');
    s.push('| ID | Trend | Adoption | Relevance | Recommendation | Applies to | Verified |\n|---|---|---|---|---|---|---|');
    for (const t of d.trends) s.push(`| ${t.id} | ${cell(t.title)} | ${t.adoption_level} | ${t.relevance} | ${t.recommendation} | ${list(t.applies_to)} | ${t.verified ? `yes (${t.last_reviewed})` : '**no**: check before client presentation'} |`);
    s.push('');
    for (const t of d.trends) {
      s.push(`### ${t.id} — ${t.title}\n\n${t.description}\n\n- **Why it matters here:** ${t.relevance_reason}`);
      s.push(t.verified ? `- **Sources:** ${t.sources.map(x => `[${x.title}](${x.url}) (accessed ${x.accessed})`).join('; ')}` : `- **Verification:** ${t.verification_note}`);
      s.push('');
    }
    out['tech-trends.md'] = s.join('\n');
  }

  // ---- risks.md ----
  {
    const s = [header('Risk register')];
    const rs = [...d.risks].sort((a, b) => RANK[b.likelihood] * RANK[b.impact] - RANK[a.likelihood] * RANK[a.impact]);
    s.push('| ID | Risk | Category | Likelihood | Impact | Mitigation | Related | Status |\n|---|---|---|---|---|---|---|---|');
    for (const k of rs) s.push(`| ${k.id} | ${cell(k.title)}${k.client_visible === false ? ' *(internal)*' : ''} | ${k.category} | ${k.likelihood} | ${k.impact} | ${cell(k.mitigation)} | ${list(k.related)} | ${k.status} |`);
    s.push('');
    out['risks.md'] = s.join('\n');
  }

  // ---- business-rules.md ----
  {
    const s = [header('Business rules')];
    const brs = live.filter(r => r.type === 'BUSINESS_RULE');
    const cats = [...new Set(brs.map(r => r.rule_category))];
    for (const c of cats) {
      s.push(`## ${c}\n`);
      for (const r of brs.filter(r => r.rule_category === c)) {
        const governs = live.filter(x => x.business_rules.includes(r.id)).map(x => x.id);
        s.push(`- **${r.id}** ${r.title} ${BADGE[r.origin]}${r.client_visible ? '' : ' *(internal)*'}: governs ${list(governs)}`);
      }
      s.push('');
    }
    if (!brs.length) s.push('None.\n');
    out['business-rules.md'] = s.join('\n');
  }

  // ---- traceability.md ----
  {
    const s = [header('Traceability')];
    s.push('## Dependency graph\n\nAn arrow points from an item to the item it depends on.\n\n```mermaid\ngraph LR');
    for (const r of live) for (const dep of r.dependencies) s.push(`  ${r.id.replace('-', '_')}["${r.id}"] --> ${dep.replace('-', '_')}["${dep}"]`);
    for (const r of live) if (!r.dependencies.length && !live.some(x => x.dependencies.includes(r.id))) s.push(`  ${r.id.replace('-', '_')}["${r.id}"]`);
    s.push('```\n');
    s.push('## Story → requirement matrix\n\n| Story | Requirement | Type | Origin | Questions | Risks |\n|---|---|---|---|---|---|');
    for (const st of d.stories) for (const r of live.filter(r => r.source.includes(st.id)))
      s.push(`| ${st.id} | ${r.id} ${cell(r.title)}${r.client_visible ? '' : ' *(internal)*'} | ${r.type} | ${BADGE[r.origin]} | ${list(r.open_questions)} | ${list(r.risks)} |`);
    const promoted = live.filter(r => r.promoted_from);
    if (promoted.length) {
      s.push('\n## Promoted from innovations\n\n| Requirement | From |\n|---|---|');
      for (const r of promoted) s.push(`| ${r.id} ${cell(r.title)} | ${r.promoted_from} |`);
    }
    s.push('');
    out['traceability.md'] = s.join('\n');
  }
  return out;
}

if (process.argv[1] && import.meta.url.endsWith(path.basename(process.argv[1]))) {
  const [src, dir] = process.argv.slice(2);
  const views = render(JSON.parse(fs.readFileSync(src, 'utf8')));
  fs.mkdirSync(dir, { recursive: true });
  for (const [f, c] of Object.entries(views)) fs.writeFileSync(path.join(dir, f), c);
  console.log(`wrote ${Object.keys(views).length} views to ${dir}`);
}
